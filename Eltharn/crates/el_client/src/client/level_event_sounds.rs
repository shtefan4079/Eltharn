use crate::client::sound_engine::SoundSource;
use el_core::resource_location::ResourceLocation;
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum PitchKind {
    Const,
    RandomSpread,
    RandomScaled,
}
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct LevelEventSound {
    pub sound: &'static str,
    pub source: SoundSource,
    pub volume: f32,
    pub pitch_kind: PitchKind,
    pub pitch_base: f32,
    pub pitch_spread: f32,
}
impl LevelEventSound {
    pub fn pitch(&self, next_float: &mut impl FnMut() -> f32) -> f32 {
        match self.pitch_kind {
            PitchKind::Const => self.pitch_base,
            PitchKind::RandomSpread => {
                let first = next_float();
                let second = next_float();
                self.pitch_base + (first - second) * self.pitch_spread
            }
            PitchKind::RandomScaled => self.pitch_base + next_float() * self.pitch_spread,
        }
    }
    pub fn event_id(&self) -> ResourceLocation {
        ResourceLocation::from_string(self.sound)
    }
}
pub const GLOBAL_EVENT_IDS: [u32; 3] = [1023, 1028, 1038];
pub fn global_event_position(camera: glam::Vec3, event_center: glam::Vec3) -> glam::Vec3 {
    let direction = event_center - camera;
    let normalized = if direction.length() < 1.0e-4 {
        glam::Vec3::ZERO
    } else {
        direction.normalize()
    };
    camera + normalized * 2.0
}

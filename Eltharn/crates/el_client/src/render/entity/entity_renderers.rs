pub fn validate_registrations<'a>(
    entity_type_paths: impl IntoIterator<Item = &'a str>,
) -> Vec<&'a str> {
    entity_type_paths
        .into_iter()
        .filter(|entity_type| {
            !matches!(*entity_type, "player" | "mannequin")
                && !has_registered_entity_renderer(entity_type)
        })
        .collect()
}
const fn renderer(entity_type: &'static str) -> RegisteredEntityRenderer {
    RegisteredEntityRenderer { entity_type }
}

#[derive(Debug, Clone, Copy)]
pub struct AvatarRenderers {
    wide: AvatarRenderer,
    slim: AvatarRenderer,
}
impl Default for AvatarRenderers {
    fn default() -> Self {
        Self::new()
    }
}
impl AvatarRenderers {
    pub const fn new() -> Self {
        Self {
            wide: AvatarRenderer::new(false),
            slim: AvatarRenderer::new(true),
        }
    }
    pub const fn get(&self, model: PlayerModelType) -> &AvatarRenderer {
        match model {
            PlayerModelType::Wide => &self.wide,
            PlayerModelType::Slim => &self.slim,
        }
    }
}

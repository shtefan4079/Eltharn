#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SwingAnimationType {
    None,
    Whack,
    Stab,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum HumanoidArm {
    Left,
    Right,
}

impl HumanoidArm {
    pub fn opposite(self) -> Self {
        match self {
            Self::Left => Self::Right,
            Self::Right => Self::Left,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum InteractionHand {
    MainHand,
    OffHand,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ArmPose {
    Empty,
    Item,
    Block,
    BowAndArrow,
    ThrowTrident,
    CrossbowCharge,
    CrossbowHold,
    Spyglass,
    TootHorn,
    Brush,
    Spear,
}

impl ArmPose {
    pub fn is_two_handed(self) -> bool {
        matches!(
            self,
            Self::BowAndArrow | Self::CrossbowCharge | Self::CrossbowHold
        )
    }

    pub fn affects_offhand_pose(self) -> bool {
        matches!(
            self,
            Self::BowAndArrow
                | Self::ThrowTrident
                | Self::CrossbowCharge
                | Self::CrossbowHold
                | Self::Spear
        )
    }
}

